"""Лексический анализатор тональности текста на русском языке.

Как это работает:
    1. текст разбивается на слова-токены (только буквы, нижний регистр, "ё" -> "е");
    2. слово сопоставляется с опорой словаря по ПРЕФИКСУ, поэтому одна запись
       покрывает все склонения: "плох" -> плохо / плохой / плохие;
    3. вес опоры правится контекстом слева: отрицанием ("не", "ни", "нет")
       и усилителем/ослабителем ("очень", "слегка");
    4. итог — баланс позитива и негатива в диапазоне [-1; 1] плюс метка,
       насыщенность и уверенность.

Никаких нейросетей, корпусов и внешних зависимостей: только словарь и
эвристики, поэтому модуль детерминирован, потокобезопасен (реестр словаря
под локом) и работает за микро/миллисекунды.

Ограничения (это ЛЕКСИЧЕСКИЙ метод):
    - сарказм и ирония ("ну просто отлично, снова упало") не распознаются;
    - смысл не зависит от объекта: "рекорд" и "рост" считаются позитивом,
      даже если это "рекорд безработицы";
    - согласование и сложные обороты ("не то чтобы плохой")Approximatively
      обрабатываются окном отрицания в CONTEXT_WINDOW слов.

Публичный API:
    analyze(text)      -> dict       — полный разбор (см. _RESULT_KEYS)
    score(text)        -> float      — балл в [-1; 1]
    label(text)        -> str        — "positive" | "negative" | "neutral"
    analyze_batch(xs)  -> list[dict] — разбор списка текстов
    aggregate(xs)      -> dict       — сводка по списку текстов
    explain(text)      -> str        — пояснение результата по-русски
    extend_lexicon(m)  -> int        — добавить доменные опоры в словарь
"""

